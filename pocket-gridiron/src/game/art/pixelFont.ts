export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const CELL_W = 7;
export const CELL_H = 9;
export const CHARS = " " + Object.keys(GLYPHS).join("");
export const PER_ROW = 16;

/** Bitmap of one glyph (true = ink). Used for drawing numbers into the field texture too. */
export function glyph(ch: string): boolean[][] {
  const g = GLYPHS[ch];
  if (!g) return Array.from({ length: GLYPH_H }, () => Array(GLYPH_W).fill(false));
  return g.split("/").map((r) => [...r].map((c) => c === "#"));
}

/** Raw glyph table (exported for validation in tests). */
export const GLYPH_TABLE: Readonly<Record<string, string>> = GLYPHS;

/** Draws text with the pixel font onto a 2D canvas context (used for baked textures). */
export function drawPixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string, shadow?: string): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = glyph(ch);
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (!g[r][c]) continue;
        if (shadow) {
          ctx.fillStyle = shadow;
          ctx.fillRect(cx + (c + 1) * scale, y + (r + 1) * scale, scale, scale);
        }
      }
    }
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (!g[r][c]) continue;
        ctx.fillStyle = color;
        ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}

export function pixelTextWidth(text: string, scale: number): number {
  return Math.max(0, text.length * (GLYPH_W + 1) * scale - scale);
}

